// Builds the gallery's catalogue from the folders in apps/, twice over:
// apps.js, which the page loads with a <script> tag so the cards draw at once
// (also when the page is opened from disk), and apps.json, the same list, which
// the page re-fetches past the HTTP cache to pick up a newer deploy.
//
//   node scripts/build-catalog.mjs
//
// Every apps/<folder>/index.html, and every loose apps/<name>.html, becomes a
// card. Loose files exist for phones: GitHub's mobile upload page can't create
// folders, but it can drop a file into apps/. Card details come from the
// app's own HTML:
//
//   name         <title>, up to the first ":", "—", "–", " - " or "|"
//   description  <meta name="description">, else the description in the
//                folder's manifest.webmanifest, else the rest of the <title>
//   accent       <meta name="theme-color">, else the manifest's theme_color
//   icon         icon-192.png, icon.png or icon.svg in the app's folder
//   tags         <meta name="gallery-tags" content="music, guitar">
//
// gallery.json can override any of these per folder, which matters for
// password-protected apps: their HTML is encrypted, so the only thing
// readable is the title given to protect.sh. The private repo's publish
// workflow writes it, adding each app's version and the dates it was added
// and last updated, which drive the gallery's New badge.
//
// Runs in the Pages deploy workflow, and locally via serve.sh. No
// dependencies, so it needs nothing beyond Node.
import { readdirSync, readFileSync, existsSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appsDir = join(root, "apps");
const overridesPath = join(root, "gallery.json");
const overrides = existsSync(overridesPath) ? JSON.parse(readFileSync(overridesPath, "utf8")) : {};

const decode = (s) =>
  s.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
   .replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
   .trim();

// Only the <head> is searched: apps are single files that can be megabytes
// long, and their bodies contain plenty of <title>/<meta> inside templates.
function head(html) {
  const end = html.search(/<\/head>|<body[\s>]/i);
  return end === -1 ? html.slice(0, 20000) : html.slice(0, end);
}

function meta(h, name) {
  for (const tag of h.match(/<meta\b[^>]*>/gi) || []) {
    const n = tag.match(/\bname\s*=\s*["']([^"']*)["']/i);
    if (n && n[1].toLowerCase() === name) {
      const c = tag.match(/\bcontent\s*=\s*"([^"]*)"|\bcontent\s*=\s*'([^']*)'/i);
      if (c) return decode(c[1] ?? c[2]);
    }
  }
  return undefined;
}

function fromFolder(folder) {
  return folder.replace(/[-_]+/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

const apps = [];
for (const entry of readdirSync(appsDir).sort()) {
  if (entry.startsWith(".")) continue;
  const path = join(appsDir, entry);
  const loose = statSync(path).isFile();
  if (loose && !entry.toLowerCase().endsWith(".html")) continue;
  // A loose file has no folder of its own, so it gets no icon or manifest.
  const folder = loose ? entry.replace(/\.html$/i, "") : entry;
  const dir = loose ? null : path;
  const file = loose ? path : join(path, "index.html");
  if (!existsSync(file)) continue;

  const html = readFileSync(file, "utf8");
  const h = head(html);
  const title = decode((h.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [])[1] || "");
  const [name, ...rest] = title.split(/\s*(?::|—|–|\s-\s|\|)\s*/);
  const icon = dir && ["icon-192.png", "icon.png", "icon.svg"].find((f) => existsSync(join(dir, f)));
  const tags = meta(h, "gallery-tags");
  let manifest = {};
  try { if (dir) manifest = JSON.parse(readFileSync(join(dir, "manifest.webmanifest"), "utf8")); } catch {}

  const app = {
    folder,
    name: name || fromFolder(folder),
    description: meta(h, "description") || manifest.description || rest.join(" — ") || "",
    url: loose ? `apps/${entry}` : `apps/${folder}/`,
    icon: icon ? `apps/${folder}/${icon}` : undefined,
    accent: meta(h, "theme-color") || manifest.theme_color,
    tags: tags ? tags.split(",").map((t) => t.trim()).filter(Boolean) : [],
    locked: /staticrypt/i.test(html.slice(0, 200000)) || undefined,
    ...overrides[folder],
  };
  // The publish workflow's record of the source it last published; the
  // gallery has no use for it.
  delete app.hash;
  apps.push(Object.fromEntries(Object.entries(app).filter(([, v]) => v !== undefined)));
}

const out =
  "// Generated by scripts/build-catalog.mjs from the folders in apps/. Don't edit;\n" +
  "// add an app by adding apps/<name>/index.html, and adjust cards in gallery.json.\n" +
  `window.APPS = ${JSON.stringify(apps, null, 2)};\n`;
writeFileSync(join(root, "apps.js"), out);
writeFileSync(join(root, "apps.json"), JSON.stringify(apps, null, 2) + "\n");
console.log(`apps.js + apps.json: ${apps.length} app(s): ${apps.map((a) => a.name).join(", ")}`);
